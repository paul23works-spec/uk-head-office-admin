import { WORKFLOW_STAGES } from './constants';

function generateWorkflow(completedUpToStageId: string, inProgressStageId?: string): ProjectWorkflowState[] {
  return WORKFLOW_STAGES.map((s) => {
    const stageNum = parseInt(s.id, 10);
    const completedNum = parseInt(completedUpToStageId, 10);
    const inProgNum = inProgressStageId ? parseInt(inProgressStageId, 10) : completedNum + 1;

    let status: 'Completed' | 'In Progress' | 'Not Started' = 'Not Started';
    let completedAt: string | undefined = undefined;

    if (stageNum <= completedNum) {
      status = 'Completed';
      completedAt = '2024-03-15';
    } else if (stageNum === inProgNum) {
      status = 'In Progress';
    }

    return {
      stageId: s.id,
      status,
      adminGroup: s.adminGroup,
      assignedUser: s.adminGroup === 'ADMIN_A' ? 'Admin A Team' : s.adminGroup === 'ADMIN_B' ? 'Admin B Team' : 'Admin C Team',
      completedAt,
      updatedAt: '2024-05-10',
      notes: status === 'In Progress' ? `Administrative processing currently active for ${s.name}.` : undefined,
    };
  });
}

